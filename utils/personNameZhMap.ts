// 内存与持久化影人缓存
export const dynamicPersonCache = new Map<string, string>();

function loadPersonCache() {
    try {
        if (typeof window !== 'undefined' && window.localStorage) {
            const raw = localStorage.getItem('cine_person_zh_cache');
            if (raw) {
                const parsed = JSON.parse(raw);
                Object.entries(parsed).forEach(([k, v]) => {
                    if (typeof v === 'string') dynamicPersonCache.set(k.toLowerCase(), v);
                });
            }
        }
    } catch {}
}

export function savePersonCache(key: string, val: string) {
    if (!key || !val) return;
    dynamicPersonCache.set(key.toLowerCase(), val);
    try {
        if (typeof window !== 'undefined' && window.localStorage) {
            const obj: Record<string, string> = {};
            dynamicPersonCache.forEach((v, k) => { obj[k] = v; });
            localStorage.setItem('cine_person_zh_cache', JSON.stringify(obj));
        }
    } catch {}
}

loadPersonCache();

/**
 * 单个影人名字本地汉化（同步方法）
 */
export function localizeSinglePersonName(name: string): string {
    if (!name || !name.trim()) return '';
    const clean = name.trim();

    // 已包含足够中文
    if (/[\u4e00-\u9fa5]{2,}/.test(clean)) {
        return clean;
    }

    const key = clean.toLowerCase().replace(/['"“”‘’]/g, '');
    if (PERSON_NAME_ZH_MAP[key]) return PERSON_NAME_ZH_MAP[key];
    if (dynamicPersonCache.has(key)) return dynamicPersonCache.get(key)!;

    // 去除点号匹配（如 Robert Downey Jr. -> Robert Downey Jr）
    const keyWithoutDot = key.replace(/\./g, '').trim();
    if (PERSON_NAME_ZH_MAP[keyWithoutDot]) return PERSON_NAME_ZH_MAP[keyWithoutDot];
    if (dynamicPersonCache.has(keyWithoutDot)) return dynamicPersonCache.get(keyWithoutDot)!;

    return clean;
}

/**
 * 将可能包含多个以逗号/斜杠/顿号分隔的影人列表进行全面汉化（同步方法）
 */
export function localizePersonNames(rawNames: string): string {
    if (!rawNames || !rawNames.trim()) return '';

    const tokens = rawNames.split(/[,，/、|]+/).map(t => t.trim()).filter(Boolean);
    if (tokens.length === 0) return '';

    const localizedTokens = tokens.map(t => localizeSinglePersonName(t));
    return localizedTokens.join(', ');
}

/**
 * 异步翻译单个或多个影人姓名（在线翻译 + 双层持久缓存）
 */
export async function translatePersonNameOnline(rawNames: string): Promise<string> {
    if (!rawNames || !rawNames.trim()) return '';
    const clean = rawNames.trim();

    // 若已经全部包含中文字符，直接返回
    const tokens = clean.split(/[,，/、|]+/).map(t => t.trim()).filter(Boolean);
    if (tokens.length === 0) return '';

    const translatedTokens = await Promise.all(tokens.map(async (token) => {
        const syncRes = localizeSinglePersonName(token);
        if (/[\u4e00-\u9fa5]/.test(syncRes)) {
            return syncRes;
        }

        const key = token.toLowerCase();
        try {
            const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=zh-CN&dt=t&q=${encodeURIComponent(token)}`;
            const res = await fetch(url);
            if (res.ok) {
                const data = await res.json();
                const translated = data?.[0]?.[0]?.[0];
                if (translated && typeof translated === 'string' && /[\u4e00-\u9fa5]/.test(translated)) {
                    const finalZh = translated.trim();
                    savePersonCache(key, finalZh);
                    return finalZh;
                }
            }
        } catch {
            // Fallback
        }

        return syncRes;
    }));

    return translatedTokens.join(', ');
}
